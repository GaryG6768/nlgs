  function getMember(){
    try{return JSON.parse(sessionStorage.getItem('nlgsMember')||'null');}
    catch(e){return null;}
  }

  function getAll(){
    try{return JSON.parse(localStorage.getItem(KEY)||'{}')||{};}
    catch(e){return {};}
  }

  function saveAll(all){
    localStorage.setItem(KEY,JSON.stringify(all));
  }

  function sameRound(a,b){
    return String(a?.date||'').slice(0,10)===String(b?.date||'').slice(0,10)
      && Math.abs(Number(a?.diff)-Number(b?.diff))<0.001;
  }

  function restoreForMember(){
    const m=getMember();
    if(!m)return false;

    const id=String(m.id||m.member_id||'').trim();
    const p=DATA[id];
    if(!p)return false;

    const all=getAll();
    const current=Array.isArray(all[id])?all[id]:[];

    const supplied=p.rounds.map(r=>({
      date:r[0]+'T12:00:00',
      diff:Number(r[1]),
      source:'manual'
    }));

    const merged=current.slice();

    supplied.forEach(r=>{
      if(!merged.some(x=>sameRound(x,r))) merged.push(r);
    });

    merged.sort((a,b)=>String(a.date||'').localeCompare(String(b.date||'')));

    const changed=JSON.stringify(current)!==JSON.stringify(merged);

    if(changed){
      all[id]=merged;
      saveAll(all);
    }

    try{
      if(typeof window.nlgsHcpRender==='function') window.nlgsHcpRender();
    }catch(e){}

    return true;
  }

  function wrapSync(){
    if(window.__nlgsCentralRecoverySyncWrapped)return;
    if(typeof window.nlgsHcpSyncRounds!=='function')return;

    const original=window.nlgsHcpSyncRounds;

    window.nlgsHcpSyncRounds=async function(){
      const result=await original.apply(this,arguments);

      setTimeout(restoreForMember,50);
      setTimeout(restoreForMember,500);
      setTimeout(restoreForMember,1500);

      return result;
    };

    window.__nlgsCentralRecoverySyncWrapped=true;
  }

  function run(){
    wrapSync();

    const m=getMember();

    if(!m){
      setTimeout(run,500);
      return;
    }

    const id=String(m.id||m.member_id||'').trim();

    if(!DATA[id]){
      setTimeout(run,1000);
      return;
    }

    restoreForMember();

    let count=0;

    const timer=setInterval(()=>{
      wrapSync();
      restoreForMember();

      count++;

      if(count>=20) clearInterval(timer);
    },500);
  }

  window.nlgsCentralBatchRecoveryV2=restoreForMember;

  run();
